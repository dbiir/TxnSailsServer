"""Read legacy benchmark-client connection fields from the unified TOML deployment.

Requires Python 3.11 or later for the standard-library TOML reader. Client workload
XML is still generated by the individual benchmark scripts.
"""

import os
from pathlib import Path
import tomllib
from xml.etree import ElementTree


DEFAULT_CONFIG = Path(__file__).resolve().parent.parent / "config" / "txnsails.toml"


def _required_text(value, field):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"Datasource configuration requires a non-empty {field}")
    return value.strip()


def _connection_fields(config_path):
    path = Path(config_path).expanduser()
    try:
        with path.open("rb") as source:
            document = tomllib.load(source)
    except (OSError, tomllib.TOMLDecodeError) as error:
        raise ValueError(f"Cannot read TOML datasource configuration: {path}") from error
    if document.get("version") != 2:
        raise ValueError("Datasource configuration requires TOML version 2")
    single = document.get("single")
    if not isinstance(single, dict):
        raise ValueError("Datasource configuration requires [single].datasource")
    reference = _required_text(single.get("datasource"), "[single].datasource reference")
    sources = document.get("datasources")
    selected = sources.get(reference) if isinstance(sources, dict) else None
    if not isinstance(selected, dict):
        raise ValueError(f"Unknown datasource reference: {reference}")
    url = _required_text(selected.get("url"), f"datasource {reference!r} URL")
    if not url.startswith("jdbc:"):
        raise ValueError(f"Datasource {reference!r} URL must be a JDBC URL")
    driver = _required_text(selected.get("driver", "org.postgresql.Driver"), "driver")
    database_type = _required_text(selected.get("type", "POSTGRES"), "type").upper()
    if database_type == "POSTGRESQL":
        database_type = "POSTGRES"
    if database_type not in {"POSTGRES", "MYSQL", "H2", "HSQLDB"}:
        raise ValueError(f"Unsupported datasource type: {database_type}")
    if database_type == "POSTGRES" and not url.startswith("jdbc:postgresql:"):
        raise ValueError("PostgreSQL datasource requires a PostgreSQL JDBC URL")
    fields = {"type": database_type, "driver": driver, "url": url}
    for field in ("username", "password"):
        value = selected.get(field, "")
        if not isinstance(value, str):
            raise ValueError(f"Datasource {reference!r} {field} must be a string")
        fields[field] = value
    return fields


def append_datasource(root, config_path=None):
    """Append connection fields from an explicit file, TXNSAILS_CONFIG, or repo default.

    Values remain raw strings: ElementTree performs the XML escaping exactly once.
    Validate the complete datasource before modifying the caller's XML element.
    """
    selected = config_path if config_path is not None else os.environ.get("TXNSAILS_CONFIG", DEFAULT_CONFIG)
    fields = _connection_fields(selected)
    for name, value in fields.items():
        ElementTree.SubElement(root, name).text = value
